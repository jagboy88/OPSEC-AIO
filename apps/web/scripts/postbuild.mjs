// Post-build hardening for the static SPA (docs/PLAN.md §7):
//
//  1. Subresource Integrity for every JS module via an import map `integrity`
//     section (covers dynamic imports too), plus `integrity` on the static
//     <link> tags. A tampered asset is refused by the browser.
//  2. A strict Content-Security-Policy with no 'unsafe-inline': the only inline
//     scripts (SvelteKit bootstrap + the import map) are allowed by SHA-256 hash.
//     Written to build-meta/csp.caddy and imported by the Caddyfile.
//  3. build-meta/build-manifest.json: SHA-256 of every served file, so users can
//     compare what they were served against the published build.
import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const BUILD = fileURLToPath(new URL('../build/', import.meta.url));
const META = fileURLToPath(new URL('../build-meta/', import.meta.url));

async function walk(dir) {
  const out = [];
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) out.push(...(await walk(p)));
    else out.push(p);
  }
  return out;
}

const urlOf = (abs) => '/' + relative(BUILD, abs).split(sep).join('/');
const digest = (alg, data) => createHash(alg).update(data).digest('base64');

const files = new Map();
for (const abs of await walk(BUILD)) files.set(urlOf(abs), await readFile(abs));

// 1. SRI
const integrity = {};
for (const [url, buf] of files) {
  if (url.startsWith('/_app/') && url.endsWith('.js'))
    integrity[url] = `sha384-${digest('sha384', buf)}`;
}
const indexPath = join(BUILD, 'index.html');
let html = files.get('/index.html').toString('utf8');
if (html.includes('type="importmap"')) throw new Error('index.html already processed');

const importMap = JSON.stringify({ imports: {}, integrity });
html = html.replace(
  '<meta charset="utf-8" />',
  `<meta charset="utf-8" />\n    <script type="importmap">${importMap}</script>`,
);
let linked = 0;
html = html.replace(
  /<link href="(\/_app\/[^"]+)" rel="(modulepreload|stylesheet)">/g,
  (_m, href, rel) => {
    const buf = files.get(href);
    if (!buf) throw new Error(`missing asset ${href}`);
    linked++;
    return `<link href="${href}" rel="${rel}" integrity="sha384-${digest('sha384', buf)}">`;
  },
);
if (linked === 0) throw new Error('no asset links found — SvelteKit output format changed?');
if (/<script[^>]*\bsrc=/.test(html))
  throw new Error('unexpected external <script src>; add SRI handling');

// 2. CSP
const inlineHashes = [...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)].map(
  (m) => `'sha256-${digest('sha256', m[1])}'`,
);
// Static style="" attributes baked into our own bundles (SvelteKit's
// screen-reader route announcer). Allowed individually via 'unsafe-hashes';
// arbitrary inline styles remain blocked.
const styleAttrs = new Set();
for (const [url, buf] of files) {
  if (!url.endsWith('.js')) continue;
  for (const m of buf.toString('utf8').matchAll(/style="([^"$`{}]+)"/g)) styleAttrs.add(m[1]);
}
if (styleAttrs.size > 3)
  throw new Error(`unexpected number of inline style attributes: ${styleAttrs.size}`);
const styleHashes = [...styleAttrs].map((s) => `'sha256-${digest('sha256', s)}'`);
const csp = [
  "default-src 'none'",
  // 'wasm-unsafe-eval' is required to instantiate libsodium's WebAssembly; it
  // does NOT permit eval() of JavaScript.
  `script-src 'self' 'wasm-unsafe-eval' ${inlineHashes.join(' ')}`,
  styleHashes.length
    ? `style-src 'self' 'unsafe-hashes' ${styleHashes.join(' ')}`
    : "style-src 'self'",
  "img-src 'self' blob:",
  "font-src 'self'",
  "connect-src 'self'",
  "worker-src 'self' blob:",
  "manifest-src 'self'",
  "base-uri 'none'",
  "form-action 'none'",
  "frame-ancestors 'none'",
].join('; ');

await writeFile(indexPath, html);
files.set('/index.html', Buffer.from(html));

await mkdir(META, { recursive: true });
await writeFile(
  join(META, 'csp.caddy'),
  `# Generated by apps/web/scripts/postbuild.mjs — do not edit.\nheader Content-Security-Policy "${csp}"\n`,
);

// 3. Manifest
const manifest = Object.fromEntries(
  [...files.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([url, buf]) => [url, createHash('sha256').update(buf).digest('hex')]),
);
const buildHash = createHash('sha256').update(JSON.stringify(manifest)).digest('hex');
await writeFile(
  join(META, 'build-manifest.json'),
  JSON.stringify({ buildHash, files: manifest }, null, 2) + '\n',
);

console.log(
  `postbuild: SRI for ${Object.keys(integrity).length} modules, ${inlineHashes.length} inline script hash(es), build ${buildHash.slice(0, 16)}…`,
);
