/** Random, unlinkable username like "quiet_otter_4821" (CSPRNG, ~23 bits). */
export function generateUsername(): string {
  const r = randomBytes(4);
  const n = ((r[2]! << 8) | r[3]!) % 10000;
  return `${ADJECTIVES[r[0]! % ADJECTIVES.length]}_${NOUNS[r[1]! % NOUNS.length]}_${String(n).padStart(4, '0')}`;
}
